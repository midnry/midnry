import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const names = [
  "models/operator-v1.glb",
  "models/props-v1.glb",
  "sky.hdr",
  ...readdirSync("public/games/military/textures")
    .filter((x) => x.endsWith(".jpg") && !x.includes("-source"))
    .map((x) => "textures/" + x),
];
const files = names.sort().map((name) => {
  const data = readFileSync("public/games/military/" + name);
  return {
    url: "/games/military/" + name,
    bytes: data.length,
    sha256: createHash("sha256").update(data).digest("hex"),
  };
});
const version = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 16);
writeFileSync(
  "public/games/outpost-asset-manifest.js",
  `/** Generated by build-outpost-cache.mjs; only public graphical assets. */\nexport const ASSET_CACHE=${JSON.stringify("outpost-assets-" + version)};\nexport const ASSET_FILES=${JSON.stringify(files, null, 2)};\n`,
);
console.log(
  JSON.stringify({
    cachedAssets: files.length,
    bytes: files.reduce((n, f) => n + f.bytes, 0),
    version,
  }),
);
