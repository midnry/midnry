import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const names = [
  "models/operator-v1.glb",
  "models/props-v1.glb",
  "models/medevac-v1.glb",
  "models/weapons-v2.glb",
  "sky.hdr",
  "textures/benchmark-operator-body-orm.png",
  "textures/benchmark-operator-skin-roughness.png",
  ...readdirSync("public/games/military/textures")
    .filter((x) => x.endsWith(".jpg") && !x.includes("-source"))
    .map((x) => "textures/" + x),
  // Arena art passes: standard textures, and the HD set used on High.
  ...readdirSync("public/games/military/models")
    .filter((x) => x.startsWith("arena-") && x.endsWith(".glb"))
    .map((x) => "models/" + x),
  ...readdirSync("public/games/military/textures/arena")
    .filter((x) => x.endsWith(".jpg"))
    .map((x) => "textures/arena/" + x),
  ...readdirSync("public/games/military/textures/arena/hd")
    .filter((x) => x.endsWith(".jpg"))
    .map((x) => "textures/arena/hd/" + x),
];
const files = names.sort().map((name) => {
  const data = readFileSync("public/games/military/" + name);
  return {
    url: "/games/military/" + name,
    bytes: data.length,
    sha256: createHash("sha256").update(data).digest("hex"),
  };
});
const version = createHash("sha256").update(JSON.stringify(files)).digest("hex").slice(0, 16);
// Locker characters load on demand (not precached): their own cache key.
const characters = createHash("sha256");
for (const name of readdirSync("public/games/military/models/characters").sort())
  characters.update(name).update(readFileSync("public/games/military/models/characters/" + name));
const characterVersion = characters.digest("hex").slice(0, 16);
writeFileSync(
  "public/games/outpost-asset-manifest.js",
  `/** Generated by build-outpost-cache.mjs; only public graphical assets. */\nexport const ASSET_CACHE=${JSON.stringify("outpost-assets-" + version)};\nexport const CHARACTER_CACHE=${JSON.stringify(characterVersion)};\nexport const ASSET_FILES=${JSON.stringify(files, null, 2)};\n`,
);
console.log(
  JSON.stringify({
    cachedAssets: files.length,
    bytes: files.reduce((n, f) => n + f.bytes, 0),
    version,
  }),
);
